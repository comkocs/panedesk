#!/usr/bin/env node
/**
 * Panedesk fork check: milestone hand-off smoke for the fork's web UI.
 * Runs the six-step keyless walk (scripts/panedesk/smoke/web-ui.smoke.ts)
 * against the current checkout through the repository's own web e2e scaffold,
 * then renders the step table and evidence index into <results-dir>/结果.md.
 *
 * Usage, from the repository root of a prepared tree (pnpm install and
 * pnpm run build:artifacts done):
 *   node scripts/panedesk/smoke/run.mjs <results-dir>
 *
 * A lane vitest config is generated into the results directory: it reuses the
 * repository's own resolution facade (vite-tsconfig-paths over
 * tsconfig.base.json) and shared decorator transform by importing them from
 * the tree, and it must stay outside the repository because the repo's
 * TypeScript programs deliberately exclude root config-plane files (a
 * committed config importing vitest.shared.ts breaks `pnpm run typecheck`),
 * while the existing lane configs pin their includes to their own trees.
 *
 * The web server binds 127.0.0.1 on an OS-assigned port and the browser is
 * headless; both are torn down at the end of the walk. No TZ or TMPDIR
 * overrides are applied; LANG and CI are pinned. The exit status is the
 * vitest run's status.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const outArg = process.argv[2]
if (outArg === undefined) {
  console.error('usage: node scripts/panedesk/smoke/run.mjs <results-dir>')
  process.exit(2)
}
const out = resolve(process.cwd(), outArg)
mkdirSync(out, { recursive: true })

const distEntry = join(root, 'apps/web/dist/index.html')
if (!existsSync(distEntry)) {
  console.error(`smoke: ${distEntry} is missing; prepare the tree first: pnpm install && pnpm run build:artifacts`)
  process.exit(2)
}

// Lane config, generated into the results directory (see the header note):
// absolute paths keep it tree-accurate wherever the results directory lives,
// and npm packages resolve through createRequire rooted at the tree because
// the results directory sits outside it.
const spec = join(root, 'scripts/panedesk/smoke/web-ui.smoke.ts')
const laneConfig = join(out, 'vitest.smoke.config.ts')
writeFileSync(laneConfig, `// Generated by scripts/panedesk/smoke/run.mjs — do not commit.
import { createRequire } from 'node:module'
import { standardDecoratorPlugin, vitestExecArgv } from ${JSON.stringify(join(root, 'vitest.shared.ts'))}

const requireFromTree = createRequire(${JSON.stringify(join(root, 'package.json'))})
const tsconfigPathsModule = requireFromTree('vite-tsconfig-paths')
const tsconfigPaths = typeof tsconfigPathsModule === 'function' ? tsconfigPathsModule : tsconfigPathsModule.default

export default {
  root: ${JSON.stringify(root)},
  plugins: [
    tsconfigPaths({ projects: [${JSON.stringify(join(root, 'tsconfig.base.json'))}] }),
    standardDecoratorPlugin(),
  ],
  test: {
    execArgv: vitestExecArgv,
    setupFiles: [${JSON.stringify(join(root, 'scripts/test-proxy-environment.ts'))}],
    include: [${JSON.stringify(spec)}],
    testTimeout: 240_000,
    hookTimeout: 240_000,
    fileParallelism: false,
  },
}
`)

// The walk itself: vitest loads the generated lane config; the spec writes
// steps.json plus per-step evidence into SMOKE_OUT as it goes.
const env = { ...process.env, LANG: 'C.UTF-8', CI: 'true', SMOKE_OUT: out }
delete env.TZ
delete env.TMPDIR
const startedAt = Date.now()
const vitest = spawnSync(join('node_modules', '.bin', 'vitest'), [
  'run',
  '--config', laneConfig,
], { cwd: root, encoding: 'utf8', env })
const vitestLog = `${vitest.stdout ?? ''}${vitest.stderr ?? ''}`
writeFileSync(join(out, 'vitest.log'), vitestLog)
process.stdout.write(vitestLog)

// Report from the spec's steps.json; a missing or short file means the walk
// was interrupted, which the rendered report must say explicitly.
const seconds = Math.round((Date.now() - startedAt) / 1000)
const git = spawnSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8' })
const commit = git.status === 0 ? git.stdout.trim() : 'unknown'
const stepsPath = join(out, 'steps.json')
const parsed = existsSync(stepsPath) ? JSON.parse(readFileSync(stepsPath, 'utf8')) : []
const steps = Array.isArray(parsed) ? parsed : []
const rows = steps.map(s =>
  `| ${s.id} | ${s.name} | ${s.pass ? '通过' : '不通过'} | ${String(s.evidence).split('\n')[0].slice(0, 160)} | ${(s.ms / 1000).toFixed(1)}s |`)
const allPass = steps.length > 0 && steps.every(s => s.pass)
const verdict = steps.length === 0 ? '未取得步骤结果(见 vitest.log)' : allPass ? '六步全部通过' : '存在不通过步骤'
const lines = [
  '# M3 冒烟结果',
  '',
  `- 构建树提交号:\`${commit}\``,
  `- 用时:${seconds}s(含配置生成与 vitest 启停)`,
  `- 总结论:**${verdict}**`,
  `- vitest 退出码:${vitest.status ?? 'spawn failed'}`,
  '',
  '| 步 | 名称 | 结论 | 证据摘要 | 用时 |',
  '| --- | --- | --- | --- | --- |',
  ...rows,
  '',
  ...(steps.length < 6 ? ['> 注:步骤结果不足 6 条,后段步骤可能被中断,详见 vitest.log。', ''] : []),
  '证据文件:各步截图 `NN_*.png`;01 步控制台明细 `01_控制台.txt`;02 步命中数 `02_heroOptions_命中.txt`;04 步 `04_轨迹文本.txt` / `04_结论.txt`。',
  '',
]
writeFileSync(join(out, '结果.md'), lines.join('\n'))

console.log(`smoke finished: exit=${vitest.status ?? 'spawn failed'}, ${seconds}s, report: ${join(out, '结果.md')}`)
process.exit(vitest.status ?? 2)
