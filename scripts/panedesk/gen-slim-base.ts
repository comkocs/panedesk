/**
 * Generate the `@panedesk/slim-base` bundle from upstream `@panedesk/dsh-base`.
 *
 * slim-base is a row-for-row subset of the dsh-base patch: every selected row,
 * including the comment block above it, is copied verbatim, so an upstream fix
 * to a shared row reaches slim by re-running this script. The bundle's
 * `dependencies` are exactly the packages those rows mount, with dsh-base's own
 * version specifiers. Panedesk-specific defaults live in `@panedesk/slim-headless`.
 *
 * Usage: `pnpm exec tsx scripts/panedesk/gen-slim-base.ts [--check]`
 * @module scripts/panedesk/gen-slim-base
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

/**
 * Rows slim mounts, in dsh-base order. The first group is the minimal set an
 * ablation run showed headless needs (boot, tools, shell, sandbox, subagent);
 * the second restores compaction, output spill, the tool-call timeout guard,
 * and AGENTS.md loading for long tasks.
 */
export const SLIM_BASE_ROWS: readonly string[] = [
  // Minimal headless core.
  'llm', 'session', 'agent', 'agent-default-model', 'llm-retry', 'llm-pi-ai',
  'session-persistence-jsonl', 'session-ledger', 'message-delivery', 'instruction-subscriptions',
  'working-directory', 'session-projection',
  'subprocess', 'sandbox', 'sandbox-policy', 'bash-sandbox', 'pwsh-sandbox',
  'approval', 'permission', 'shell-env', 'tool-bash', 'tool-pwsh',
  'fs-observation-policy', 'tool-fs', 'tool-fs-search',
  'subagent', 'subagent-spawn-in-process', 'tool-subagent',
  'session-checkpoint-policy', 'tools', 'system-prompt', 'agent-loop', 'fs-sandbox',
  // Restored for long tasks.
  'agent-instructions', 'token-meter', 'compaction-basic', 'timeout-policy',
  'spill-local', 'spill-policy', 'tool-result-pruner',
]

const ROOT = resolve(import.meta.dirname, '../..')
const BASE_DIR = resolve(ROOT, 'packages/bundle/base')
const SLIM_DIR = resolve(ROOT, 'packages/bundle/slim-base')

const HEADER = `# GENERATED by scripts/panedesk/gen-slim-base.ts from packages/bundle/base/cordis.patch.yml.
# Do not edit by hand: change SLIM_BASE_ROWS in the script and re-run it.
#
# The @panedesk/slim-base bundle patch: a verbatim row subset of dsh-base,
# applied as ONE insert over the empty profile root. It keeps the minimal
# headless core plus compaction, output spill, the tool-call timeout guard, and
# AGENTS.md loading. Rows absent here (Web/API gateway, telemetry, DeepSeek
# account and request extensions, skills, goals, workflow, web tools, ...) are
# what the full preset adds back through @panedesk/dsh-base.
`

interface RowBlock {
  readonly id: string
  readonly text: string
}

/** Split the single insert list of the dsh-base patch into per-row text blocks. */
function splitRows(patch: string): RowBlock[] {
  const lines = patch.split('\n')
  const start = lines.indexOf('- insert:')
  if (start < 0) throw new Error('gen-slim-base: dsh-base patch has no top-level insert list')
  const blocks: RowBlock[] = []
  let pending: string[] = []
  let current: { id: string; lines: string[] } | undefined
  const flush = (): void => {
    if (current === undefined) return
    while (current.lines.at(-1) === '') current.lines.pop()
    blocks.push({ id: current.id, text: current.lines.join('\n') })
    current = undefined
  }
  for (const line of lines.slice(start + 1)) {
    const row = /^ {4}- id: (\S+)\s*$/.exec(line)
    if (row !== null) {
      flush()
      current = { id: row[1] as string, lines: [...pending, line] }
      pending = []
      continue
    }
    if (line === '' || /^ {4}#/.test(line)) {
      // Blank lines and row-level comments belong to the next row's preamble
      // unless more body lines of the current row follow them.
      pending.push(line)
      continue
    }
    if (current === undefined) throw new Error(`gen-slim-base: unexpected line before the first row: ${line}`)
    current.lines.push(...pending, line)
    pending = []
  }
  flush()
  return blocks.map(block => ({ id: block.id, text: block.text.replace(/^\n+/, '') }))
}

/** Package name a row's `name` mounts: the bare package of a subpath export. */
function rowPackage(text: string): string {
  const match = /^ {6}name: '([^']+)'/m.exec(text)
  if (match === null) throw new Error(`gen-slim-base: row without a quoted name:\n${text}`)
  const parts = (match[1] as string).split('/')
  const first = parts[0] as string
  return first.startsWith('@') ? `${first}/${parts[1]}` : first
}

/** Render the slim-base patch text and dependency map. */
export function renderSlimBase(): { patch: string; dependencies: Record<string, string> } {
  const basePatch = readFileSync(resolve(BASE_DIR, 'cordis.patch.yml'), 'utf8').replaceAll('\r\n', '\n')
  const baseManifest = JSON.parse(readFileSync(resolve(BASE_DIR, 'package.json'), 'utf8')) as { dependencies: Record<string, string> }
  const rows = new Map(splitRows(basePatch).map(block => [block.id, block]))
  const selected = SLIM_BASE_ROWS.map((id) => {
    const block = rows.get(id)
    if (block === undefined) throw new Error(`gen-slim-base: dsh-base has no row ${JSON.stringify(id)}`)
    return block
  })
  // Keep dsh-base order so diffs against upstream stay readable.
  const order = [...rows.keys()]
  selected.sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id))
  const dependencies: Record<string, string> = {}
  for (const block of selected) {
    const name = rowPackage(block.text)
    const spec = baseManifest.dependencies[name]
    if (spec === undefined) throw new Error(`gen-slim-base: dsh-base does not depend on ${name} (row ${block.id})`)
    dependencies[name] = spec
  }
  const body = selected.map(block => block.text).join('\n\n')
  return { patch: `${HEADER}\n- insert:\n${body}\n`, dependencies: Object.fromEntries(Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b))) }
}

function main(): void {
  const check = process.argv.includes('--check')
  const { patch, dependencies } = renderSlimBase()
  const patchPath = resolve(SLIM_DIR, 'cordis.patch.yml')
  const manifestPath = resolve(SLIM_DIR, 'package.json')
  const manifestText = readFileSync(manifestPath, 'utf8')
  const manifest = JSON.parse(manifestText) as Record<string, unknown>
  manifest['dependencies'] = dependencies
  const nextManifest = `${JSON.stringify(manifest, null, 2)}\n`
  let currentPatch = ''
  try { currentPatch = readFileSync(patchPath, 'utf8') } catch { /* first generation */ }
  if (check) {
    const stale = [currentPatch === patch ? undefined : patchPath, manifestText === nextManifest ? undefined : manifestPath].filter(Boolean)
    if (stale.length > 0) {
      console.error(`gen-slim-base: stale ${stale.join(', ')}; run pnpm exec tsx scripts/panedesk/gen-slim-base.ts`)
      process.exit(1)
    }
    console.log(`gen-slim-base: up to date (${String(SLIM_BASE_ROWS.length)} rows, ${String(Object.keys(dependencies).length)} packages)`)
    return
  }
  writeFileSync(patchPath, patch)
  writeFileSync(manifestPath, nextManifest)
  console.log(`gen-slim-base: wrote ${String(SLIM_BASE_ROWS.length)} rows, ${String(Object.keys(dependencies).length)} packages`)
}

if (import.meta.main) main()
